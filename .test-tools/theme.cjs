const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const context = await browser.newContext({ colorScheme: 'light', viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const url = 'file:///C:/claude_code_projects/exp-07-markdown-previewer/index.html';
  const theme = () => page.locator('html').getAttribute('data-theme');
  await page.goto(url);
  await page.waitForSelector('#preview table');
  assert.equal(await theme(), 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.emulateMedia({ colorScheme: 'light' });
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'light');
  const source = await page.locator('#editor').inputValue();
  const toggle = page.getByRole('switch', { name: 'Dark mode' });
  await toggle.focus();
  await page.keyboard.press('Space');
  assert.equal(await theme(), 'dark');
  assert.equal(await toggle.getAttribute('aria-checked'), 'true');
  await page.waitForFunction(() => getComputedStyle(document.body).backgroundColor === 'rgb(20, 28, 24)');
  assert.equal(await page.locator('#editor').inputValue(), source);
  await page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))));
  await page.screenshot({ path: path.join(__dirname, 'dark-desktop.png'), fullPage: true });
  await page.reload();
  await page.waitForSelector('#preview table');
  assert.equal(await theme(), 'dark');
  await page.emulateMedia({ colorScheme: 'light' });
  assert.equal(await theme(), 'dark'); // Explicit choice wins.
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => Promise.all(document.getAnimations().map(animation => animation.finished.catch(() => {}))));
  await page.screenshot({ path: path.join(__dirname, 'dark-mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.studio').evaluate(el => getComputedStyle(el).animationName), 'none');
  assert.equal(await page.locator('.theme-thumb').evaluate(el => getComputedStyle(el).transitionDuration), '0s');
  await toggle.click();
  assert.equal(await theme(), 'light');
  await toggle.focus();
  await page.keyboard.press('Enter');
  assert.equal(await theme(), 'dark');
  await page.reload();
  assert.equal(await theme(), 'dark');
  const blocked = await browser.newPage({ colorScheme: 'dark' });
  await blocked.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked'); } }));
  await blocked.route('https://cdn.jsdelivr.net/**', route => route.abort());
  await blocked.goto(url);
  assert.equal(await blocked.locator('html').getAttribute('data-theme'), 'dark');
  await blocked.getByRole('switch', { name: 'Dark mode' }).click();
  assert.equal(await blocked.locator('html').getAttribute('data-theme'), 'light');
  assert.deepEqual(errors, []);
  console.log('PASS: system default and changes, keyboard Space/Enter, theme persistence and precedence, source preservation, dark desktop/mobile, no mobile overflow, reduced motion, blocked storage and unavailable CDN. No page errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
