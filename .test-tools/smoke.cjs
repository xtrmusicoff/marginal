const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('file:///C:/claude_code_projects/exp-07-markdown-previewer/index.html');
  await page.waitForSelector('#preview table');
  assert.equal(await page.locator('#preview h1').textContent(), 'A little room for ideas');
  await page.screenshot({ path: path.join(__dirname, 'desktop.png'), fullPage: true });
  await page.locator('#editor').fill('# Test\n\n**bold** and *italic*\n\n- one\n  - nested\n\n```js\nconst x = 1;\n```\n\n| A | B |\n|---|---|\n| 1 | 2 |');
  await page.waitForSelector('#preview table');
  assert.equal(await page.locator('#preview strong').textContent(), 'bold');
  assert.equal(await page.locator('#preview ul ul').count(), 1);
  assert.match(await page.locator('#preview pre').textContent(), /const x = 1/);
  await page.getByText('Draft saved in this browser', { exact: true }).waitFor();
  await page.reload();
  await page.waitForSelector('#preview table');
  assert.match(await page.locator('#editor').inputValue(), /# Test/);
  const malicious = '# Safe\n\n<script>window.pwned=1</script><img src=x onerror="window.pwned=2"><a href="javascript:window.pwned=3">bad</a><iframe src="https://example.com"></iframe><style>body{display:none}</style>';
  await page.locator('#editor').fill(malicious);
  assert.equal(await page.locator('#preview script, #preview img, #preview iframe, #preview style, #preview [onerror], #preview a[href^="javascript:"]').count(), 0);
  assert.equal(await page.evaluate(() => window.pwned), undefined);
  page.once('dialog', d => d.dismiss());
  await page.locator('#clear').click();
  assert.equal(await page.locator('#editor').inputValue(), malicious);
  page.once('dialog', d => d.accept());
  await page.locator('#clear').click();
  assert.equal(await page.locator('#editor').inputValue(), '');
  await page.getByText('Draft saved in this browser', { exact: true }).waitFor();
  await page.reload();
  await page.waitForSelector('#preview .empty');
  assert.equal(await page.locator('#editor').inputValue(), '');
  await page.locator('#sample').click();
  await page.waitForSelector('#preview table');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'untitled.md');
  await download.saveAs(path.join(__dirname, 'download.md'));
  assert.equal(require('node:fs').readFileSync(path.join(__dirname, 'download.md'), 'utf8'), await page.locator('#editor').inputValue());
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(__dirname, 'mobile.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const sourceBox = await page.locator('.editor-pane').boundingBox();
  const previewBox = await page.locator('.preview-pane').boundingBox();
  assert(previewBox.y >= sourceBox.y + sourceBox.height - 1);
  assert.deepEqual(errors, []);
  const offline = await browser.newPage();
  await offline.route('https://cdn.jsdelivr.net/**', r => r.abort());
  await offline.addInitScript(() => Object.defineProperty(window, 'localStorage', { get() { throw new Error('blocked'); } }));
  await offline.goto('file:///C:/claude_code_projects/exp-07-markdown-previewer/index.html');
  await offline.getByText('Preview unavailable', { exact: true }).waitFor();
  await offline.locator('#editor').fill('Still editable');
  assert.equal(await offline.locator('#editor').inputValue(), 'Still editable');
  console.log('PASS: sample, live formatting, nested lists/code/tables, persistence including empty drafts, sanitization, confirmations, reset, exact download, mobile stacking/no overflow, missing dependencies and blocked storage. No page errors.');
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
